import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const appDir = path.join(root, 'app');
const outDir = path.join(root, 'www');
const apiBaseUrl = String(process.env.ARCANA_API_BASE_URL || '').trim().replace(/\/+$/, '');

if (apiBaseUrl) {
  try {
    const parsed = new URL(apiBaseUrl);
    if (!['http:', 'https:'].includes(parsed.protocol)) throw new Error('protocol');
  } catch (error) {
    console.error('ARCANA_API_BASE_URL must be an http(s) URL, for example https://api.example.com');
    process.exit(1);
  }
} else {
  console.warn('ARCANA_API_BASE_URL is empty. The Android app will not be able to reach a backend until you rebuild with a URL.');
}

fs.rmSync(outDir, { recursive: true, force: true });
fs.mkdirSync(outDir, { recursive: true });
fs.cpSync(appDir, outDir, { recursive: true });

const sharedSource = path.join(root, 'shared', 'tarot.js');
const sharedTarget = path.join(outDir, 'shared', 'tarot.js');
fs.mkdirSync(path.dirname(sharedTarget), { recursive: true });
fs.copyFileSync(sharedSource, sharedTarget);

fs.writeFileSync(
  path.join(outDir, 'js', 'runtime-config.js'),
  `/* Generated by scripts/build-web.mjs. */\nwindow.ARCANA_CONFIG = {\n  apiBaseUrl: ${JSON.stringify(apiBaseUrl)}\n};\n`,
  'utf8'
);

const files = [];
function walk(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full);
    else files.push({ full, size: fs.statSync(full).size });
  }
}
walk(outDir);
const bytes = files.reduce((sum, file) => sum + file.size, 0);
console.log(`www ready: ${files.length} files, ${(bytes / 1024 / 1024).toFixed(2)} MB`);
console.log(`API base: ${apiBaseUrl || '(same origin / not configured)'}`);
